"""Stdlib-only verifier for the transfer-tests study.

Run from the artifact root, with the study's pinned interpreter (CPython 3.12.14):
    python3.12 -B -S studies/transfer-tests/verify_transfer_tests.py --results results/transfer-tests

The variant regeneration uses tokenize.untokenize, whose output for two modules
(defusedxml-04, jmespath-05; rename and name collapse) differs between CPython
3.12.3 and 3.12.14. The audited bytes and all test runs use 3.12.14; on another
interpreter these four regenerated_hash checks are reported as SKIPPED (the
audited-hash checks of the same cells still run), and every other mismatch fails.

Checks, and exits nonzero on any mismatch:
  * every frozen module in corpus/transfer matches its manifest sha256, and the
    three variants regenerated from it (covewm.extended, artifact-local stdlib
    code) match both the retained audit hashes
    (results/controlled/raw/project_transfer.csv) and the variant_sha256 in
    every raw record;
  * the raw records cover exactly 24 projects x 5 modules x 3 interventions;
  * project eligibility follows from the recorded baseline runs, and the
    baseline-passing sets (baseline/*.json.gz) match their recorded sizes/hashes;
  * every cell's outcome follows from its recorded attempts under the protocol
    rules, and reported test ids are members of the project's baseline set;
  * every number in summary.json is recomputed independently from the raw
    records.
"""
from __future__ import annotations

import argparse
import csv
import gzip
import hashlib
import json
import sys
from pathlib import Path

INTERVENTIONS = ("inert-trailing-comment", "syntax-aware-local-rename", "scope-blind-identifier-collapse")
KEYWORD_PATTERNS = ("unexpected keyword argument", "got multiple values for argument")
OUTCOMES = ("preserved", "contradicted", "unavailable")


def sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


class Checker:
    def __init__(self) -> None:
        self.failures: list[str] = []
        self.passed = 0

    def require(self, cond: bool, label: str, detail: object = "") -> None:
        if cond:
            self.passed += 1
        else:
            self.failures.append(f"{label} {detail}".strip())


# Cells whose regenerated bytes depend on the CPython patch level (tokenize.untokenize).
TOKENIZE_SENSITIVE = {
    ("defusedxml-04", "syntax-aware-local-rename"), ("defusedxml-04", "scope-blind-identifier-collapse"),
    ("jmespath-05", "syntax-aware-local-rename"), ("jmespath-05", "scope-blind-identifier-collapse"),
}


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def regenerate(artifact: Path) -> dict[tuple[str, str], str] | None:
    sys.path.insert(0, str(artifact / "src"))
    try:
        from covewm.extended import (  # type: ignore
            inert_trailing_comment,
            scope_blind_identifier_collapse,
            syntax_aware_local_rename,
        )
    except Exception:
        return None
    out = {}
    with (artifact / "corpus/transfer_manifest.csv").open(encoding="utf-8", newline="") as handle:
        manifest = list(csv.DictReader(handle))
    for rec in manifest:
        path = artifact / "corpus/transfer" / rec["project_slug"] / f"module-{int(rec['selection_rank']):02d}.py"
        source = path.read_text(encoding="utf-8")
        out[(rec["module_id"], "__source__")] = sha(source)
        out[(rec["module_id"], "inert-trailing-comment")] = sha(inert_trailing_comment(source))
        out[(rec["module_id"], "syntax-aware-local-rename")] = sha(syntax_aware_local_rename(
            source, int(rec["rename_function_line"]), rec["rename_parameter"], "cvlocal" + rec["source_sha256"][:7]))
        out[(rec["module_id"], "scope-blind-identifier-collapse")] = sha(scope_blind_identifier_collapse(source))
        out[(rec["module_id"], "__manifest__")] = rec["source_sha256"]
    return out


def expected_outcome(cell: dict, eligible: bool) -> tuple[str, str]:
    if not eligible:
        return "unavailable", "project ineligible"
    attempts = cell.get("attempts")
    if not attempts:
        return "unavailable", cell.get("reason", "")
    if any(a["timed_out"] for a in attempts):
        return "unavailable", "timeout"
    if attempts[0]["not_preserved"] == 0:
        return "preserved", ""
    if len(attempts) < 2:
        return "invalid", "missing confirmation rerun"
    if cell.get("reproducible_breaks", 0) > 0:
        return "contradicted", ""
    return "unavailable", "failures did not reproduce"


def keyword_break(cell: dict) -> bool:
    if cell["outcome"] != "contradicted":
        return False
    for a in cell.get("attempts", []):
        msgs = [m["message"] for m in a.get("not_preserved_messages", [])] + a.get("collect_error_messages", [])
        if any(p in m for m in msgs for p in KEYWORD_PATTERNS):
            return True
    return False


def recompute_summary(runs: list[dict], projects: list[dict]) -> dict:
    eligible = sorted(p["project"] for p in projects if p["eligible"])
    elig = set(eligible)

    def ex(c: dict, key: str = "exercised") -> bool:
        be = c.get("baseline_exercise")
        return bool(be) and bool(be[key])

    per = {}
    for iv in INTERVENTIONS:
        cells = [c for c in runs if c["intervention"] == iv]
        by_reason: dict[str, int] = {}
        for c in cells:
            if c["outcome"] == "unavailable":
                k = c["reason"].split(":")[0]
                by_reason[k] = by_reason.get(k, 0) + 1
        per[iv] = {
            "cells": len(cells),
            "cells_in_eligible_projects": len([c for c in cells if c["project"] in elig]),
            "modules_with_suites_exercising_them": len([c for c in cells if ex(c)]),
            "preserved": len([c for c in cells if c["outcome"] == "preserved" and ex(c)]),
            "contradicted": len([c for c in cells if c["outcome"] == "contradicted"]),
            "contradicted_exercised": len([c for c in cells if c["outcome"] == "contradicted" and ex(c)]),
            "contradicted_not_exercised": len([c for c in cells if c["outcome"] == "contradicted" and not ex(c)]),
            "unavailable": len([c for c in cells if c["outcome"] == "unavailable"]),
            "unavailable_by_reason": by_reason,
            "not_exercised": len([c for c in cells if c["outcome"] == "preserved" and not ex(c)]),
            "keyword_break_cells": len([c for c in cells if keyword_break(c)]),
            "contradicted_module_ids": sorted(c["module_id"] for c in cells if c["outcome"] == "contradicted"),
        }
    first = [c for c in runs if c["intervention"] == INTERVENTIONS[0]]
    drift = {}
    for p in projects:
        if p["eligible"]:
            pcs = p.get("post_controls") or []
            drift[p["project"]] = max((pc["drift"] if pc["drift"] is not None else -1) for pc in pcs) if pcs else None
    return {
        "study": "transfer-tests",
        "protocol": "studies/transfer-tests/protocol.json",
        "deviations": "studies/transfer-tests/deviations.json",
        "deviation_projects": sorted(p["project"] for p in projects if p.get("deviation")),
        "projects_attempted": len(projects),
        "projects_eligible": len(eligible),
        "eligible_projects": eligible,
        "ineligible_projects": {p["project"]: p["ineligible_reason"] for p in projects if not p["eligible"]},
        "modules_attempted": len(first),
        "modules_in_eligible_projects": len([c for c in first if c["project"] in elig]),
        "modules_imported_by_suite": len([c for c in first if ex(c, "imported")]),
        "modules_exercised_by_suite": len([c for c in first if ex(c)]),
        "rename_target_function_executed": len([c for c in first if ex(c, "target_function_executed")]),
        "cells": len(runs),
        "variant_runs_executed": sum(len(c.get("attempts", [])) for c in runs),
        "baseline_passing_tests": {p["project"]: p["baseline_passing"] for p in projects if p["eligible"]},
        "baseline_passing_tests_total": sum(p["baseline_passing"] for p in projects if p["eligible"]),
        "post_control_max_drift": drift,
        "keyword_patterns": list(KEYWORD_PATTERNS),
        "per_intervention": per,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", type=Path, required=True)
    ap.add_argument("--artifact", type=Path, default=Path(__file__).resolve().parents[2])
    args = ap.parse_args()
    results, artifact = args.results, args.artifact
    ck = Checker()

    protocol = json.loads((artifact / "studies/transfer-tests/protocol.json").read_text(encoding="utf-8"))
    ck.require(protocol.get("status") == "pre-declared", "protocol::status")
    runs = read_jsonl(results / "runs.jsonl")
    projects = read_jsonl(results / "projects.jsonl")
    summary = json.loads((results / "summary.json").read_text(encoding="utf-8"))

    # population
    ck.require(len(projects) == 24 and len({p["project"] for p in projects}) == 24, "population::projects", len(projects))
    ck.require(len(runs) == 360, "population::cells", len(runs))
    keys = {(c["module_id"], c["intervention"]) for c in runs}
    ck.require(len(keys) == 360, "population::unique_cells")
    with (artifact / "corpus/transfer_manifest.csv").open(encoding="utf-8", newline="") as handle:
        manifest = {r["module_id"]: r for r in csv.DictReader(handle)}
    ck.require(keys == {(m, iv) for m in manifest for iv in INTERVENTIONS}, "population::matches_manifest")

    # variant bytes
    with (artifact / "results/controlled/raw/project_transfer.csv").open(encoding="utf-8", newline="") as handle:
        audited = {(r["module_id"], r["intervention"]): r["candidate_sha256"] for r in csv.DictReader(handle)}
    regen = regenerate(artifact)
    ck.require(regen is not None, "variants::regenerator_importable")
    skipped: list[tuple[str, str]] = []
    for c in runs:
        k = (c["module_id"], c["intervention"])
        ck.require(c["variant_sha256"] == audited.get(k), "variants::audited_hash", k)
        ck.require(c["source_sha256"] == manifest[c["module_id"]]["source_sha256"], "variants::source_hash_record", k)
        if regen is not None:
            ck.require(regen[(c["module_id"], "__source__")] == regen[(c["module_id"], "__manifest__")], "variants::corpus_module_hash", k)
            if regen[k] != c["variant_sha256"] and k in TOKENIZE_SENSITIVE and sys.version_info[:3] != (3, 12, 14):
                skipped.append(k)
                continue
            ck.require(regen[k] == c["variant_sha256"], "variants::regenerated_hash",
                       (k, "interpreter " + sys.version.split()[0] + "; audited bytes use CPython 3.12.14"))

    # projects and baselines
    baselines: dict[str, set[str]] = {}
    elig_map = {}
    for p in projects:
        runs_b = p.get("baseline_runs") or []
        complete = (p["setup_status"] == "ok" and len(runs_b) == 2
                    and all((not r["timed_out"]) and r["counts"]["passed"] > 0 for r in runs_b))
        ck.require(complete == p["eligible"], "eligibility::rule", p["project"])
        elig_map[p["project"]] = p["eligible"]
        if p["eligible"]:
            with gzip.open(results / "baseline" / f"{p['project']}.json.gz", "rt", encoding="utf-8") as handle:
                data = json.load(handle)
            base = data["baseline_passing"]
            ck.require(base == sorted(set(base)), "baseline::sorted_unique", p["project"])
            ck.require(len(base) == p["baseline_passing"], "baseline::size", p["project"])
            ck.require(sha("\n".join(base)) == p["baseline_passing_sha256"], "baseline::sha", p["project"])
            ck.require(len(base) <= min(r["counts"]["passed"] for r in runs_b), "baseline::within_runs", p["project"])
            ck.require(not (set(base) & set(data["flaky_excluded"])), "baseline::flaky_disjoint", p["project"])
            baselines[p["project"]] = set(base)
        else:
            ck.require(bool(p["ineligible_reason"]), "eligibility::reason", p["project"])

    # cells
    for c in runs:
        k = (c["module_id"], c["intervention"])
        ck.require(c["outcome"] in OUTCOMES, "cell::outcome_label", k)
        out, reason = expected_outcome(c, elig_map[c["project"]])
        ck.require(c["outcome"] == out, "cell::outcome_rule", (k, c["outcome"], out))
        if out == "unavailable" and reason:
            ck.require(c["reason"].startswith(reason), "cell::reason", (k, c["reason"], reason))
        if c.get("attempts"):
            base = baselines[c["project"]]
            ck.require(c.get("restored_ok") is True, "cell::restored", k)
            ck.require(len(c["attempts"]) == (2 if (c["attempts"][0]["not_preserved"] > 0 and not c["attempts"][0]["timed_out"]) else 1), "cell::attempt_count", k)
            for a in c["attempts"]:
                ck.require(0 <= a["not_preserved"] <= len(base), "cell::not_preserved_bound", k)
                ck.require(set(a["not_preserved_ids"]) <= base, "cell::ids_in_baseline", k)
                ck.require(len(a["not_preserved_ids"]) == min(25, a["not_preserved"]), "cell::ids_truncation", k)
                if a["not_preserved"] == 0 and not a["timed_out"]:
                    ck.require(a["not_preserved_sha256"] == sha(""), "cell::empty_hash", k)
                cnt = a["counts"]
                ck.require(cnt["run"] == cnt["passed"] + cnt["failed"] + cnt["error"] + cnt["xfailed"] + cnt["xpassed"], "cell::counts_run", k)
                if not a["timed_out"]:
                    # every baseline-passing test that passed is counted in 'passed'
                    ck.require(cnt["passed"] >= len(base) - a["not_preserved"], "cell::passed_vs_not_preserved", k)
            if "reproducible_breaks" in c:
                ck.require(c["reproducible_breaks"] <= min(a["not_preserved"] for a in c["attempts"]), "cell::repro_bound", k)
                ck.require(set(c["reproducible_break_ids"]) <= base, "cell::repro_in_baseline", k)
        else:
            ck.require(c["outcome"] == "unavailable", "cell::no_attempts_unavailable", k)
        if c.get("baseline_exercise") is not None:
            ck.require(elig_map[c["project"]], "cell::exercise_only_eligible", k)
        be = c.get("baseline_exercise")
        if be and be["exercised"]:
            ck.require(be["functions_executed"] > 0, "cell::exercise_consistency", k)

    # rename cells share the per-module exercise record with the other interventions
    by_mod: dict[str, list] = {}
    for c in runs:
        by_mod.setdefault(c["module_id"], []).append(json.dumps(c.get("baseline_exercise"), sort_keys=True))
    ck.require(all(len(set(v)) == 1 for v in by_mod.values()), "cell::exercise_per_module")

    # summary
    recomputed = recompute_summary(runs, projects)
    for key in sorted(set(recomputed) | set(summary)):
        ck.require(recomputed.get(key) == summary.get(key), "summary::" + key, "")
    total = {o: sum(1 for c in runs if c["outcome"] == o) for o in OUTCOMES}
    ck.require(sum(total.values()) == 360, "summary::partition")

    if ck.failures:
        for f in ck.failures[:50]:
            print("FAIL", f)
        print(f"transfer-tests verification FAILED: {len(ck.failures)} failing checks, {ck.passed} passing")
        return 1
    if skipped:
        print(f"SKIPPED regenerated_hash for {len(skipped)} tokenize-sensitive cells on interpreter "
              f"{sys.version.split()[0]} (audited bytes use CPython 3.12.14; audited-hash checks still passed): "
              + ", ".join(f"{m}/{i}" for m, i in sorted(skipped)))
    per = summary["per_intervention"]
    print(f"transfer-tests verification passed: {ck.passed} checks; "
          f"{summary['projects_eligible']}/24 projects eligible; "
          + "; ".join(f"{iv}: preserved={per[iv]['preserved']} contradicted={per[iv]['contradicted']} "
                      f"unavailable={per[iv]['unavailable']} not_exercised={per[iv]['not_exercised']}" for iv in INTERVENTIONS))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
